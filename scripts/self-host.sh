#!/bin/sh
# githug on your own Cloudflare account (docs/SELF_HOSTING.md, mode 1).
#
#   scripts/self-host.sh [--name githug] [--domain githug.example.com] [--dry-run]
#
# Creates (or reuses) the D1 database, KV namespaces and R2 bucket, writes wrangler.self.jsonc,
# applies migrations, sets generated secrets (saved to .selfhost.env, 0600), deploys, and prints
# the one-click GitHub App setup URL. Re-running is safe. Needs `npx wrangler login` first.
# --dry-run: no Cloudflare changes; writes the config with placeholder ids and bundles it.
set -eu
cd "$(dirname "$0")/.."

NAME=githug
DOMAIN=""
DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    --domain) DOMAIN="$2"; shift 2 ;;
    --dry-run) DRY=1; shift ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done
CFG=wrangler.self.jsonc
W="npx --yes wrangler"
say() { printf '\033[32m▸\033[0m %s\n' "$*"; }
die() { echo "self-host: $*" >&2; exit 1; }

[ -d node_modules ] || npm ci
if [ "$DRY" = 1 ]; then
  DB_ID=00000000-0000-0000-0000-000000000000; CACHE_ID=00000000000000000000000000000000
else
  $W whoami >/dev/null 2>&1 || die "not logged in: run npx wrangler login"
  say "D1 database $NAME"
  DB_ID=$($W d1 list --json | node -e 'const l=JSON.parse(require("fs").readFileSync(0,"utf8"));const d=l.find(x=>x.name===process.argv[1]);process.stdout.write(d?d.uuid:"")' "$NAME")
  [ -n "$DB_ID" ] || { $W d1 create "$NAME" >/dev/null; DB_ID=$($W d1 list --json | node -e 'const l=JSON.parse(require("fs").readFileSync(0,"utf8"));process.stdout.write(l.find(x=>x.name===process.argv[1]).uuid)' "$NAME"); }
  kv() {
    id=$($W kv namespace list 2>/dev/null | node -e 'const l=JSON.parse(require("fs").readFileSync(0,"utf8"));const n=l.find(x=>x.title===process.argv[1]);process.stdout.write(n?n.id:"")' "$1")
    [ -n "$id" ] || id=$($W kv namespace create "$1" 2>&1 | grep -oE '[0-9a-f]{32}' | head -1)
    [ -n "$id" ] || die "could not create KV namespace $1"
    echo "$id"
  }
  say "KV namespace"
  CACHE_ID=$(kv "$NAME-CACHE")
  say "R2 bucket $NAME-releases"
  $W r2 bucket create "$NAME-releases" >/dev/null 2>&1 || true
fi

say "writing $CFG"
NAME="$NAME" DOMAIN="$DOMAIN" DB_ID="$DB_ID" CACHE_ID="$CACHE_ID" node -e '
const e = process.env;
const cfg = {
  name: e.NAME,
  main: "src/worker.ts",
  compatibility_date: "2026-06-01",
  compatibility_flags: ["nodejs_compat"],
  assets: { directory: "./public", binding: "ASSETS", run_worker_first: ["/"] },
  rules: [{ type: "Text", globs: ["**/*.md"], fallthrough: true }],
  kv_namespaces: [{ binding: "CACHE", id: e.CACHE_ID }],
  d1_databases: [{ binding: "DB", database_name: e.NAME, database_id: e.DB_ID }],
  r2_buckets: [{ binding: "RELEASES", bucket_name: e.NAME + "-releases" }],
  ratelimits: [
    { name: "WRITE_LIMITER", namespace_id: "1002", simple: { limit: 30, period: 60 } },
    { name: "VERIFY_LIMITER", namespace_id: "1003", simple: { limit: 300, period: 60 } },
  ],
  triggers: { crons: ["17 */4 * * *"] },
  vars: { GITHUG_MODE: "self-hosted", ...(e.DOMAIN ? { GITHUG_ORIGIN: "https://" + e.DOMAIN } : {}) },
  ...(e.DOMAIN ? { routes: [{ pattern: e.DOMAIN, custom_domain: true }] } : { workers_dev: true }),
  observability: { enabled: true },
};
require("fs").writeFileSync("wrangler.self.jsonc", "// Generated by scripts/self-host.sh — safe to re-run.\n" + JSON.stringify(cfg, null, 2) + "\n");
'

if [ "$DRY" = 1 ]; then
  say "dry run: bundling"
  $W deploy --config "$CFG" --dry-run --outdir .wrangler/selfhost-dry >/dev/null
  say "ok: $CFG is valid and the Worker bundles. Re-run without --dry-run to deploy."
  exit 0
fi

say "migrations"
$W d1 migrations apply "$NAME" --remote --config "$CFG"

say "secrets"
umask 077
touch .selfhost.env
have() { $W secret list --config "$CFG" 2>/dev/null | grep -q "\"$1\""; }
secret() {
  have "$1" && return 0
  printf '%s' "$2" | $W secret put "$1" --config "$CFG" >/dev/null
  printf '%s=%s\n' "$1" "$2" >> .selfhost.env
}
secret GATEWAY_ENC_KEY "$(openssl rand -base64 32)"
secret STATS_USER admin
secret STATS_PASSWORD "$(openssl rand -base64 18 | tr -d '/+=')"
secret ADMIN_TOKEN "$(openssl rand -hex 32)"

say "deploying"
OUT=$($W deploy --config "$CFG" 2>&1) || {
  # The cron trigger can fail on its own (the Workers free plan has 5 per account); the Worker
  # is still live. Crons only re-check agent scope and sync PR outcomes, so warn and go on.
  echo "$OUT" | grep -q "^Uploaded $NAME" || { echo "$OUT"; die "deploy failed"; }
  echo "$OUT" | grep -q "triggers failed" && echo "  warning: the cron trigger didn't deploy (free plan: 5 cron triggers per account). githug works without it; scheduled scope re-checks and PR-outcome sync won't run." >&2
}
URL=$(echo "$OUT" | grep -oE 'https://[^ ]+\.workers\.dev' | head -1)
[ -n "$DOMAIN" ] && URL="https://$DOMAIN"

echo
say "githug is up: $URL"
echo "  1. Create its GitHub App (one click): $URL/gateway/setup/github-app"
echo "     login: admin / the STATS_PASSWORD in .selfhost.env"
echo "  2. In the App's settings on GitHub, tick 'Enable Device Flow' (for hug login)."
echo "  3. Sign in at $URL/login, install the App on your repos, create an agent."
echo "  CLI: curl -fsSL $URL/install | sh && hug init --repo owner/repo --url $URL"
